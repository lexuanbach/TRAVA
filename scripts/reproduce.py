#!/usr/bin/env python3
"""Replay cached analyses in an isolated copy, without model generation."""
import argparse
import datetime
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import time
from verify_snapshot import ROOT, verify

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--suite", choices=["core", "full"], default="core")
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    output = args.output.resolve()
    if output == ROOT or ROOT.is_relative_to(output):
        ap.error("output must not be the repository or its parent")
    if output.exists() and any(output.iterdir()):
        ap.error("output directory is not empty; choose a new run directory")
    integrity = verify()
    if integrity["failures"]:
        print(json.dumps(integrity, indent=2)); return 1
    output.mkdir(parents=True, exist_ok=True)
    work = output / "work"
    work.mkdir()
    for name in ["pipeline", "annotation", "configs", "data", "results"]:
        shutil.copytree(ROOT / name, work / name,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    logs = output / "logs"; logs.mkdir()
    stages = json.loads((ROOT / "scripts/stages.json").read_text())
    records = []
    summary = {"suite": args.suite, "started_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
               "scope": "CPU analysis of cached answers and labels; no model or human generation",
               "python": sys.version, "stages": records, "integrity": integrity}
    env = dict(os.environ, HF_HUB_OFFLINE="1", TRANSFORMERS_OFFLINE="1",
               OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1", TOKENIZERS_PARALLELISM="false",
               PYTHONDONTWRITEBYTECODE="1")
    for s in stages:
        if args.suite not in s["suites"]: continue
        rec = {"id": s["id"], "title": s["title"], "command": [sys.executable, s["script"], *s["args"]],
               "results": s["results"]}
        print("Running:", s["title"], flush=True)
        start = time.monotonic()
        with (logs / (s["id"] + ".log")).open("w") as log:
            try:
                p = subprocess.run(rec["command"], cwd=work, env=env, stdout=log,
                                   stderr=subprocess.STDOUT, timeout=1800)
                rec.update(exit_code=p.returncode, status="successful" if p.returncode == 0 else "failed")
            except subprocess.TimeoutExpired:
                rec.update(status="failed", reason="1800-second timeout")
        rec["seconds"] = round(time.monotonic() - start, 2)
        records.append(rec)
        print(" ", rec["status"], rec["seconds"], "seconds", flush=True)
        (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    for i, why in [("fresh_tokenization", "External tokenizer/GGUF assets are not distributed"),
                   ("model_generation", "Frozen model answers and model labels are replay inputs"),
                   ("human_annotation", "No new human judgments are generated by this workflow")]:
        records.append({"id": i, "status": "skipped", "reason": why})
    summary["counts"] = {k: sum(x["status"] == k for x in records) for k in ["successful", "failed", "skipped"]}
    (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary["counts"], indent=2))
    return int(summary["counts"]["failed"] > 0)
if __name__ == "__main__":
    raise SystemExit(main())
